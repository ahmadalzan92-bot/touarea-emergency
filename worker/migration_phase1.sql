-- Users table
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  username TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  salt TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'viewer',
  failed_attempts INTEGER DEFAULT 0,
  locked_until INTEGER,
  last_login INTEGER,
  created_at INTEGER NOT NULL
);

-- Audit log table
CREATE TABLE IF NOT EXISTS audit_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user TEXT NOT NULL,
  action TEXT NOT NULL,
  target TEXT,
  details TEXT,
  ip TEXT,
  ts INTEGER NOT NULL
);

-- Create default admin user (password: Admin@123456789 - CHANGE IN PRODUCTION!)
-- Salt and hash will be generated by the register endpoint
-- For initial setup, use the /api/auth/register endpoint with admin credentials

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_audit_user ON audit_log(user);
CREATE INDEX IF NOT EXISTS idx_audit_ts ON audit_log(ts);
CREATE INDEX IF NOT EXISTS idx_users_username ON users(username);
